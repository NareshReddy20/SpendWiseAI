import React, { useState, useEffect } from 'react';
import { getTransactions } from '../../services/transactionService';
import { getAIInsights } from '../../services/aiService';
import Card from '../../components/common/Card';
import EmptyState from '../../components/common/EmptyState';

const AIInsights = () => {
  const [insights, setInsights] = useState([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const transactions = getTransactions();
    const aiInsights = getAIInsights(transactions);
    setInsights(aiInsights);
    setLoading(false);
  }, []);

  const getIconForType = (type) => {
    const icons = {
      spending: '📊',
      trend: '📈',
      positive: '🌟',
      warning: '⚠️',
      general: '💡'
    };
    return icons[type] || '💡';
  };

  if (loading) {
    return <div style={{ textAlign: 'center', padding: '40px' }}>Loading insights...</div>;
  }

  return (
    <div>
      <h2 style={{ marginBottom: '20px' }}>AI Financial Insights</h2>
      <p style={{ color: '#666', marginBottom: '24px' }}>
        Smart insights based on your spending patterns and financial data.
      </p>

      {insights.length === 0 ? (
        <EmptyState message="No insights available yet" icon="🤖" />
      ) : (
        <div style={{ display: 'grid', gap: '16px' }}>
          {insights.map((insight, index) => (
            <Card key={index}>
              <div style={{ display: 'flex', alignItems: 'flex-start', gap: '12px' }}>
                <div style={{ fontSize: '24px' }}>{getIconForType(insight.type)}</div>
                <div>
                  <p style={{ fontSize: '16px' }}>{insight.message}</p>
                  <small style={{ color: '#999', marginTop: '4px', display: 'block' }}>
                    Generated by SpendWise AI
                  </small>
                </div>
              </div>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
};

export default AIInsights;